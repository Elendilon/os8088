def fp(c, X, Y, z):
    """a point at height z AS WRITTEN in down.bbc -> picture px (the compile subtracts the rebase)"""
    return D.floor_point(c, X, Y, z - ZB[0])


def set_rebase(text):
    ZB[0] = B.parse(text, COURSE).zbase


def wall_top(wx, wy):
    with open(COURSE, encoding="ascii") as f:
        for ln in f:
            m = re.match(r"wall\s+tile\s+(-?\d+)\s+(-?\d+)\s+flat\s+([\d.]+)", ln)
            if m and (int(m.group(1)), int(m.group(2))) == (wx, wy):
                return float(m.group(3))
    raise SystemExit("art.py: no rail block at (%d, %d) in down.bbc" % (wx, wy))


def text_px(t, ink=K):
    """one line in the tree's 8 x 8 face, PROPORTIONAL (each glyph its inked width, one blank column between,
    a space 3): -> ({(x, y): ink}, width, height 6) - the glyphs' blank top and bottom rows trimmed"""
    out, x = {}, 0
    for ch in t:
        g = B.label_glyph(ch, 0, 0, ink)
        if ch == " " or not g:
            x += 3
            continue
        xs = [p[0] for p in g]
        a, b = min(xs), max(xs) + 1
        for (gx, gy), _ in g.items():
            out[(x + gx - a, gy - 1)] = ink
        x += b - a + 1
    ys = [p[1] for p in out] or [0]
    return out, x - 1, max(ys) + 1


def outlined(cells, fill):
    """{(x, y)} -> {(x, y): colour}, its 4-neighbour edge black"""
    return {(x, y): (K if any((x + dx, y + dy) not in cells for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))
                     else fill(x, y)) for (x, y) in cells}


# ---- the planes: a bitmap drawn flat, then sheared into a face of the scene ------------------------------
def paste_y(a, c, Yf, X0, ztop, bm):
    """into the upright plane y = Yf (a +y face, or a board along +x): u px along +x from X0, v px down from
    ztop; the plane recedes one row down for every two columns right"""
    sx0, sy0 = fp(c, X0, Yf, ztop)
    for (u, v), col in bm.items():
        a.px[(int(sx0) + u, int(sy0) + v + u // 2)] = col


def paste_x(a, c, Xf, Y0, ztop, bm, host=None):
    """into the upright plane x = Xf (a +x face, or a board along +y): u px to the screen's RIGHT from the
    point (Xf, Y0, ztop) - which is toward -y, so the plane RISES one row for every two columns right"""
    sx0, sy0 = fp(c, Xf, Y0, ztop)
    for (u, v), col in bm.items():
        x, y = int(sx0) + u, int(sy0) + v - (u + 1) // 2
        if host is None or D.owner_at(x, y) in host:
            a.px[(x, y)] = col


def floor_paint(c, rect, z, glyph, scale):
    """paint on a FLOOR rect (x0 y0 x1 y1) at height z: glyph(u, v) -> colour or None, u = (X - x0) * scale,
    v = (Y - y0) * scale (floor coordinates in 1/scale tiles); only on the rect's own cells, so nothing in front
    of the floor is painted"""
    x0, y0, x1, y1 = rect
    a = D.Art(host={(x, y) for x in range(x0, x1) for y in range(y0, y1)})
    zf = lambda X, Y: z - ZB[0]
    pts = [fp(c, X, Y, z) for X in (x0, x1) for Y in (y0, y1)]
    for sy in range(int(min(p[1] for p in pts)) - 1, int(max(p[1] for p in pts)) + 2):
        for sx in range(int(min(p[0] for p in pts)) - 1, int(max(p[0] for p in pts)) + 2):
            if D.owner_at(sx, sy) not in a.host:
                continue
            X, Y = D.unproject_floor(c, sx + 0.5, sy + 0.5, zf)
            if not (x0 <= X < x1 and y0 <= Y < y1):     # the floor's TOP only, not its faces
                continue
            v = glyph((X - x0) * scale, (Y - y0) * scale)
            if v is not None:
                a.px[(sx, sy)] = v
    return a


def floor_shape(c, rect, z, inside, colour):
    """a filled floor shape, one-pixel black line (decals.Art.outline on the rect's own cells)"""
    x0, y0, x1, y1 = rect
    a = D.Art(host={(x, y) for x in range(x0, x1) for y in range(y0, y1)})
    zf = lambda X, Y: z - ZB[0]
    pts = [fp(c, X, Y, z) for X in (x0, x1) for Y in (y0, y1)]
    a.outline(lambda sx, sy: inside(*D.unproject_floor(c, sx, sy, zf)),
              lambda sx, sy: colour(*D.unproject_floor(c, sx + 0.5, sy + 0.5, zf)),
              (int(min(p[0] for p in pts)) - 1, int(min(p[1] for p in pts)) - 1,
               int(max(p[0] for p in pts)) + 2, int(max(p[1] for p in pts)) + 2))
    return a


# ---- the SIGNS ---------------------------------------------------------------------------------------------
def ball_icon(kind):
    """a 13 x 13 BALL: steel - white with a black-banded sheen and a magenta core shade, heavy; glass - cyan
    with a white glint and two white facet lines"""
    r = 6
    cells = {(x, y) for y in range(-r, r + 1) for x in range(-r, r + 1) if x * x + y * y <= r * r + 2}

    def fill(x, y):
        if kind == "steel":
            if (x + 2) ** 2 + (y + 2) ** 2 <= 3:
                return W
            if x + y > 4:
                return M
            return K if x - y in (2, 3) else W
        if (x + 2) ** 2 + (y + 3) ** 2 <= 2:
            return W
        if y == x + 1 or y == -x + 4:
            return W
        return C
    return {(x + r, y + r): v for (x, y), v in outlined(cells, fill).items()}, 13, 13


def arrow_board(content, w_in, h_in, tip):
    """a BOARD shaped as an arrow: a white plank, a magenta stripe top and bottom, black-lined, its point at
    the `tip` end ("l" or "r"), the content (a {(x, y): colour}) on it.  -> ({(x, y): colour}, w, h)"""
    h = h_in + 6
    pl = h // 2 + 1                                   # the point's length
    w = w_in + 6 + pl
    cells = set()
    for y in range(h):
        d = abs(y - (h - 1) / 2.0)
        for x in range(w):
            k = (w - 1 - x) if tip == "r" else x       # distance from the tip end
            if k >= pl or d <= k * (h / 2.0) / pl:
                cells.add((x, y))

    def fill(x, y):
        return M if y in (1, h - 2) else W
    px = outlined(cells, fill)
    ox = (pl if tip == "l" else 0) + 3
    for (x, y), v in content.items():
        px[(ox + x, 3 + y)] = v
    return px, w, h


def signpost(c, style):
    """a FORK SIGNPOST on the rail block POST (the hub's east corner, beside the steel exit): a banded post and
    two arrow boards level on the screen - STEEL higher, pointing RIGHT (the steel exit runs down-right from
    the pads), GLASS lower, pointing LEFT (the membrane is left of the post, a little down); style "fork" the
    words, "balls" a picture of each ball instead"""
    a = D.Art()
    wx, wy = POST
    bx, by = fp(c, wx + 0.5, wy + 0.5, wall_top(wx, wy))
    bx, by = int(bx), int(by)
    if style == "fork":
        s, sw, sh = text_px("STEEL")
        g, gw, gh = text_px("GLASS")
    else:
        s, sw, sh = ball_icon("steel")
        g, gw, gh = ball_icon("glass")
    sb, w1, h1 = arrow_board(s, sw, sh, "r")
    gb, w2, h2 = arrow_board(g, gw, gh, "l")
    top = by - 14 - h1 - h2 - 4                        # the upper board's top row (the lower clears the block by 14)
    for y in range(top - 3, by + 1):                   # the post: black, white with black bands, black
        a.px[(bx - 1, y)] = K
        a.px[(bx, y)] = K if (by - y) % 7 == 6 else W
        a.px[(bx + 1, y)] = K
    for dx in (-1, 0, 1):                              # a magenta cap
        a.px[(bx + dx, top - 4)] = K
    a.px[(bx, top - 3)] = M
    for (x, y), v in sb.items():                       # STEEL: from the post, right
        a.px[(bx - 2 + x, top + y)] = v
    for (x, y), v in gb.items():                       # GLASS: under it, left
        a.px[(bx + 3 - w2 + x, top + h1 + 3 + y)] = v
    return a


def fat_text(word, ink):
    """text_px's word with every stroke a pixel taller (a floor squashes rows 2:1, so a 1-px row is lost)"""
    t, tw, th = text_px(word, ink)
    out = dict(t)
    for (x, y) in t:
        out[(x, y + 1)] = ink
    return out, tw, th + 1


def keyline_word(word, x0, y0):
    """a word WHITE with a black keyline round every stroke (it reads on any face, and on the Hercules):
    -> {(x, y): colour}, the word's top-left glyph pixel at (x0, y0)"""
    ink, tw, th = text_px(word, W)
    word_px = {(x0 + u, y0 + v) for (u, v) in ink}
    bm = {}
    for (u, v) in word_px:
        for du in (-1, 0, 1):
            for dv in (-1, 0, 1):
                bm[(u + du, v + dv)] = K
    for q in word_px:
        bm[q] = W
    return bm, tw, th


def wall_words(c, Yf, X0, X1, ztop, word, host):
    """a word and an arrow PAINTED on an upright +y face (plane y = Yf, from x X0 to X1, its top ztop), sheared
    with it, pointing +x (along the face, down-right on the screen): "WORD >", centred on the face"""
    bm, tw, th = keyline_word(word, 0, 0)
    ah = {}                                            # the arrowhead: 4 px deep, a keyline
    cells = {(tw + 3 + k, th // 2 + d) for k in range(5) for d in range(-(4 - k), 4 - k + 1)}
    for (u, v) in cells:
        for du in (-1, 0, 1):
            for dv in (-1, 0, 1):
                ah.setdefault((u + du, v + dv), K)
    for q in cells:
        ah[q] = W
    bm.update({q: v for q, v in ah.items() if v == K and q not in bm})
    bm.update({q: v for q, v in ah.items() if v == W})
    w = tw + 9
    span = int(16 * (X1 - X0))
    u0 = (span - w) // 2
    a = D.Art()
    sx0, sy0 = fp(c, X0, Yf, ztop)
    for (u, v), col in bm.items():
        x, y = int(sx0) + u0 + u, int(sy0) + 4 + v + (u0 + u) // 2
        if D.owner_at(x, y) in host:
            a.px[(x, y)] = col
    return a


