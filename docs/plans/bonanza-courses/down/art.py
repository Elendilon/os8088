def floor_arrow_panel(c, host, z, centre, word, scale):
    """a PANEL painted on a floor, the word in it reading along +x, centred on the floor point `centre`"""
    ink_px, tw, th = fat_text(word, W)
    pw, ph = tw + 6, th + 6
    zf = lambda X, Y: z - ZB[0]
    cX, cY = centre
    a = D.Art(host=host)

    def uv(sx, sy):
        X, Y = D.unproject_floor(c, sx, sy, zf)
        return (X - cX) * scale + pw / 2.0, (Y - cY) * scale + ph / 2.0

    def inside(sx, sy):
        if (lambda X, Y: (int(math.floor(X)), int(math.floor(Y))))(*D.unproject_floor(c, sx, sy, zf)) not in host:
            return False
        u, v = uv(sx, sy)
        return 0 <= u < pw and 0 <= v < ph and not ((u < 1.5 or u >= pw - 1.5) and (v < 1.5 or v >= ph - 1.5))

    def colour(sx, sy):
        u, v = uv(sx, sy)
        return W if (int(u - 3), int(v - 3)) in ink_px else M
    ends = [fp(c, cX + dx, cY + dy, z) for dx in (-3, 3) for dy in (-3, 3)]
    a.outline(inside, colour, (int(min(p[0] for p in ends)), int(min(p[1] for p in ends)),
                               int(max(p[0] for p in ends)), int(max(p[1] for p in ends))))
    return a


def lift(c):
    """on H's +x face beside the lift (the run's west wall, plane x 62): a fat UP ARROW over LIFT, painted with
    the face (sheared with it), white, black-lined"""
    a = D.Art()
    Xf, (ya, yb), zlo, zhi = HFACE
    wid = int(16 * (yb - ya))                           # the face's run in px (two tiles: 32)
    cxm = wid // 2
    cells = set()
    for v in range(3, 15):                              # the arrow: a head 6 rows, a shaft 3 wide
        half = (v - 3) + 1 if v < 9 else 2
        for u in range(cxm - half, cxm + half + 1):
            cells.add((u, v))
    bm = outlined(cells, lambda u, v: W)
    ink, tw, th = text_px("LIFT", W)                    # the word: white, a black keyline round every stroke
    word = {(cxm - tw // 2 + u, 18 + v) for (u, v) in ink}
    for (u, v) in word:
        for du in (-1, 0, 1):
            for dv in (-1, 0, 1):
                bm.setdefault((u + du, v + dv), K)
    for q in word:
        bm[q] = W
    paste_x(a, c, Xf, yb, zhi, bm, HFACE_CELLS)
    return a


def chequer_flag(a, bx, by, tall=36, fw=18, fh=12, flip=False):
    """a CHEQUERED FLAG on a pole from (bx, by) up: the pole white between black, the cloth black and white
    squares of 2 px with a wave, a magenta knob"""
    for y in range(by - tall, by + 1):
        a.px[(bx - 1, y)] = K
        a.px[(bx, y)] = W
        a.px[(bx + 1, y)] = K
    for dx in (-1, 0, 1):
        a.px[(bx + dx, by - tall - 2)] = K
        a.px[(bx + dx, by - tall - 1)] = M if dx == 0 else K
    d = -1 if flip else 1
    cells = {}
    for u in range(fw):
        wave = int(round(1.5 * math.sin(u * 0.45)))
        for v in range(fh):
            cells[(u, v + wave)] = W if ((u // 2) + (v // 2)) % 2 else K
    got = set(cells)
    for (u, v), col in cells.items():
        edge = any((u + du, v + dv) not in got for du, dv in ((1, 0), (-1, 0), (0, 1), (0, -1)))
        a.px[(bx + d * (2 + u), by - tall + 1 + v)] = K if edge else col


