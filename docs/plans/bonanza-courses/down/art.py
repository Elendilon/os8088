# ---- assembling a variant ------------------------------------------------------------------------------------
_CAPTURED = []
_OWNERS = {}


def owners(text, path):
    """compile the course and keep the canvas that says which cell drew each pixel (decals' owner buffer)"""
    if not _CAPTURED:
        D.capture_render()
        _CAPTURED.append(1)
    set_rebase(text)
    if text in _OWNERS:
        D.CANVAS[:] = [_OWNERS[text][1]]
        return _OWNERS[text][0]
    D.CANVAS[:] = []
    mode, B._CACHE["mode"] = B._CACHE["mode"], "w"      # (a cache HIT would bring no canvas: write only)
    try:
        c = B.compile_course(text, path)
    finally:
        B._CACHE["mode"] = mode
    cvs = [cv for cv in D.CANVAS if cv.w == 8 * c.cols]
    if not cvs:
        raise SystemExit("art.py: the compile came from the cache without its canvas; run with BB_CACHE=0")
    _OWNERS[text] = (c, cvs[-1])
    D.CANVAS[:] = [cvs[-1]]
    return c


def build(signs, extras, outdir, prefix="down_"):
    """write outdir/down.bbc and its .bba files (named PREFIX...): the course with THIS ART block; -> its path"""
    with open(COURSE, encoding="ascii") as f:
        src = f.read()
    src = OLD.sub("", src).rstrip("\n") + "\n"
    path = os.path.join(outdir, "down.bbc")
    c = owners(src, COURSE)
    pieces = []
    if signs in ("fork", "balls"):
        pieces.append((prefix + "sign", signpost(c, signs), "the SPLIT's signpost (%s)" % signs))
    elif signs == "wall":
        pieces.append((prefix + "sign", wall_signs(c), "the SPLIT's words painted on the walls"))
    for e in extras:
        f, note = PIECES[e]
        pieces.append((prefix + e, f(c), note))
    lines = [BEGIN]
    for name, art, note in pieces:
        if not art.px:
            raise SystemExit("art.py: %s drew nothing" % name)
        fn = name + ".bba"
        ax, ay = art.write(os.path.join(outdir, fn), note)
        with open(os.path.join(outdir, fn), encoding="ascii") as f:
            body = f.read().replace("first/decals.py", "down/art.py")
        with open(os.path.join(outdir, fn), "w", encoding="ascii", newline="\n") as f:
            f.write(body)
        lines.append("art %s %d %d" % (fn, ax, ay))
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write(src + "\n".join(lines) + "\n" + END + "\n")
    return path


# ---- measuring ---------------------------------------------------------------------------------------------
def measure(path):
    """compile a variant (its .bba files read from its own folder) -> (course, figures): the picture part's RAM
    bytes (one SHEET's, every sheet the same size), the sheet plan, the blocks, and every part packed LZB"""
    keep = B.COURSE_DIR
    B.COURSE_DIR = os.path.dirname(os.path.abspath(path))
    try:
        with open(path, encoding="ascii") as f:
            c = B.compile_course(f.read() + "# measured in %s\n" % B.COURSE_DIR, path)
    finally:
        B.COURSE_DIR = keep
    sheets = list(c.sstored) if c.sstored else [c.stored]
    plan = "%d x %d rows from %s" % (c.plan["k"], c.plan["n"], ",".join(str(s["m0"]) for s in c.plan["sheets"])) \
        if c.sstored else "one picture part"
    return c, {"pic": len(c.cga), "plan": plan, "blocks": len(c.blocks), "world": len(c.wcga) if c.split else 0,
               "lzb": [B.packed_len(s, "lzb") for s in sheets] + ([B.packed_len(c.wstored, "lzb")] if c.split else [])}


def pictures(c, Image):
    cga = Image.new("RGB", (c.width, c.lines))
    cga.putdata([P1[v] for r in c.pic for v in r])
    h = Image.new("L", (c.width * 2, c.lines))
    data = []
    for y, row in enumerate(c.pic):
        for x, v in enumerate(row):
            pr = B.herc_pair(v, y, x)
            data += [255 * (pr >> 1), 255 * (pr & 1)]
    h.putdata(data)
    return cga, h.convert("RGB")


ZOOM = 4


def crop_pair(cga, herc, box, Image, zoom=ZOOM):
    x0, y0, x1, y1 = box
    a = cga.crop(box).resize(((x1 - x0) * zoom, (y1 - y0) * zoom), Image.NEAREST)
    b = herc.crop((2 * x0, y0, 2 * x1, y1)).resize(((x1 - x0) * zoom, (y1 - y0) * zoom), Image.NEAREST)
    return a, b


def grid(rows, Image, ImageDraw, title, head):
    pad, top = 8, 44
    cw = [max(r[1][k].width for r in rows) for k in range(len(rows[0][1]))]
    rh = [max(im.height for im in r[1]) + 22 for r in rows]
    Wd = sum(cw) + pad * (len(cw) + 1)
    H = top + sum(rh) + pad * (len(rows) + 1)
    sheet = Image.new("RGB", (Wd, H), (40, 40, 48))
    d = ImageDraw.Draw(sheet)
    d.text((pad, 6), title, fill=(255, 255, 255))
    x = pad
    for k, t in enumerate(head):
        d.text((x, 26), t, fill=(200, 200, 200))
        x += cw[k] + pad
    y = top + pad
    for (lab, ims), h in zip(rows, rh):
        d.text((pad, y), lab, fill=(255, 255, 160))
        x = pad
        for k, im in enumerate(ims):
            sheet.paste(im, (x, y + 18))
            x += cw[k] + pad
        y += h + pad
    return sheet


def art_box(path, margin=16):
    """the picture box round every `art` of a variant (from its .bbc and .bba files), with a margin"""
    xs, ys = [], []
    d = os.path.dirname(path)
    with open(path, encoding="ascii") as f:
        for ln in f:
            m = re.match(r"art (\S+) (\d+) (\d+)", ln)
            if m:
                rows = [r for r in open(os.path.join(d, m.group(1)), encoding="ascii").read().split("\n")
                        if r and not r.startswith("#")]
                x, y = int(m.group(2)), int(m.group(3))
                xs += [x, x + len(rows[0])]
                ys += [y, y + len(rows)]
    return [min(xs) - margin, min(ys) - margin, max(xs) + margin, max(ys) + margin]


VARIANTS = [("none", "none", ())] + [("sign-" + s, s, ()) for s in SIGN_STYLES if s != "none"] + \
           [("decal-" + e, "none", (e,)) for e in EXTRAS] + \
           [("set-suggested", "fork", ("stairs", "sink", "lift", "flags"))]     # a modest set, all at once


def _one(job):
    name, sg, ex, out = job
    d = os.path.join(out, name)
    os.makedirs(d, exist_ok=True)
    for fn in os.listdir(d):
        if fn.endswith(".bba"):
            os.remove(os.path.join(d, fn))
    p = build(sg, ex, d, "dx" + re.sub(r"[^a-z0-9]", "", name)[:10] + "_")
    c, m = measure(p)
    return name, p, Owners(None, c), m                 # (the picture alone: a Course does not pickle)


def sheet(out, jobs=2):
    from PIL import Image, ImageDraw
    import multiprocessing
    os.makedirs(out, exist_ok=True)
    with open(COURSE, encoding="ascii") as f:          # the owner buffer once, before the workers fork
        owners(OLD.sub("", f.read()).rstrip("\n") + "\n", COURSE)
    work = [(n, sg, ex, out) for n, sg, ex in VARIANTS]
    if jobs > 1:
        with multiprocessing.get_context("fork").Pool(jobs) as pool:
            got = pool.map(_one, work, chunksize=1)
    else:
        got = [_one(w) for w in work]
    res = {n: (p, c, m) for n, p, c, m in got}
    base = res["none"][2]
    lines = ["variant         picture part  delta  blocks  delta  sheets                   LZB per part (sheets, world)"]
    for n, (p, c, m) in res.items():
        lines.append("%-15s %12d %+6d %7d %+6d  %-24s %s" % (n, m["pic"], m["pic"] - base["pic"], m["blocks"],
                                                             m["blocks"] - base["blocks"], m["plan"],
                                                             " ".join("%d" % v for v in m["lzb"])))
    txt = "\n".join(lines) + "\n"
    with open(os.path.join(out, "costs.txt"), "w") as f:
        f.write(txt)
    print(txt)
    pics = {n: pictures(c, Image) for n, (p, c, m) in res.items()}

    def lab(n):
        m = res[n][2]
        return "%s   picture part %+d bytes a sheet (%d new blocks); LZB %+d over all parts" % (
            n.split("-", 1)[1].upper(), m["pic"] - base["pic"], m["blocks"] - base["blocks"],
            sum(m["lzb"]) - sum(base["lzb"]))
    for group, names, fname in (("SIGNS at the split", [n for n in res if n.startswith("sign-")], "signs.png"),
                                ("INTEREST DECALS", [n for n in res if n.startswith("decal-")], "decals.png")):
        rows = []
        for n in names:
            box = art_box(res[n][0])
            z = ZOOM if (box[2] - box[0]) * (box[3] - box[1]) < 40000 else 2
            rows.append((lab(n) + ("   (x2)" if z == 2 else ""),
                         [crop_pair(*pics["none"], box, Image, z)[0]] + list(crop_pair(*pics[n], box, Image, z))))
        grid(rows, Image, ImageDraw, "DOWNHILL DECISION - %s; palette 1 (CGA: cyan, magenta, white on black) and "
             "Hercules; x%d" % (group, ZOOM), ["without (CGA)", "with (CGA)", "with (Hercules)"]).save(
            os.path.join(out, fname))
    for n in res:
        pics[n][0].save(os.path.join(out, n, "full-cga.png"))
        pics[n][1].save(os.path.join(out, n, "full-herc.png"))
    print("sheet: %s" % out)


class Owners:
    """the canvas's owner buffer alone (what decals.owner_at reads), or the course's picture and origin alone
    (what the pieces read), which pickle"""

    def __init__(self, cv, c=None):
        if cv is not None:
            self.obuf, self.w, self.h = cv.obuf, cv.w, cv.h
        else:
            self.pic, self.width, self.lines, self.x0, self.y0, self.cols = c.pic, c.width, c.lines, c.x0, c.y0, c.cols


def preview(out):
    """a QUICK look while drawing, no compile per option: every option's pixels laid straight over the course's
    picture (the base compile and its owner buffer kept in OUT/base.pkl), crops into OUT/preview-*.png.  NOT a
    measurement - `sheet` compiles each option for real"""
    import pickle
    from PIL import Image
    os.makedirs(out, exist_ok=True)
    pk = os.path.join(out, "base.pkl")
    with open(COURSE, encoding="ascii") as f:
        src = OLD.sub("", f.read()).rstrip("\n") + "\n"
    if os.path.exists(pk):
        with open(pk, "rb") as f:
            c, cv = pickle.load(f)
        _OWNERS[src] = (c, cv)
        D.CANVAS[:] = [cv]
        set_rebase(src)
    else:
        c = owners(src, COURSE)
        cv = Owners(_OWNERS[src][1])
        c = Owners(None, c)
        with open(pk, "wb") as f:
            pickle.dump((c, cv), f)
    opts = [("sign-" + s, lambda s=s: signpost(c, s) if s != "wall" else wall_signs(c))
            for s in ("fork", "balls", "wall")] + [("decal-" + e, lambda e=e: PIECES[e][0](c)) for e in EXTRAS]
    print("rebase", ZB[0])
    for n, f in opts:
        a = f()
        if not a.px:
            print("%-14s drew NOTHING" % n)
            continue
        pic = [list(r) for r in c.pic]
        for (x, y), v in a.px.items():
            if 0 <= y < c.lines and 0 <= x < c.width:
                pic[y][x] = v
        xs = [p[0] for p in a.px]
        ys = [p[1] for p in a.px]
        box = (min(xs) - 24, min(ys) - 24, max(xs) + 24, max(ys) + 24)

        class _P:
            pass
        q = _P()
        q.pic, q.width, q.lines = pic, c.width, c.lines
        cga, herc = pictures(q, Image)
        a_, b_ = crop_pair(cga, herc, box, Image)
        im = Image.new("RGB", (a_.width * 2 + 8, a_.height), (40, 40, 48))
        im.paste(a_, (0, 0))
        im.paste(b_, (a_.width + 8, 0))
        im.save(os.path.join(out, "preview-%s.png" % n))
        print("%-14s box %s, block rows %d - %d" % (n, box, (box[1] + 24) // 8, (box[3] - 24) // 8))
    pictures(c, Image)[0].save(os.path.join(out, "base-cga.png"))


