"""FIRST ROLL's ART prototypes (the owner, 2026-11-18: "make some art
prototypes on the course; it needs to fit in, look natural; so same style as
the general art and game, and high quality").

Host-only and deterministic, nothing in `make` runs it: the artwork's SOURCE
(CLAUDE.md, "treat artwork as source"). It draws shapes in WORLD
coordinates - on a floor plane, or on an upright plane for a banner - and
projects them with the tool's own projection (a point (X, Y) at height z
units is picture pixel (16 (X - Y) + x0, 8 (X + Y) - 8 z + y0); a cell's
centre is (wx + 0.5, wy + 0.5)). Each piece is filled in the course's four
colours (0 black, 1 cyan, 2 magenta, 3 white) with a ONE-pixel black outline,
the game's line. Art takes the occlusion of the surface it is painted on
(SPEC.md 137.23.2), so a decal on a floor IS that floor.

    python3 docs/plans/bonanza-courses/first/decals.py

writes apps/bonanza/courses/roll_*.bba and replaces the block between the
ART markers at the end of apps/bonanza/courses/roll.bbc (geometry first -
the frame's pillars, the lone pillars - then the `art` lines, whose picture
coordinates come from compiling the course with that geometry in)."""
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import bbcourse as B                                   # noqa: E402

COURSE = os.path.join(ROOT, "apps", "bonanza", "courses", "roll.bbc")
CDIR = os.path.dirname(COURSE)
BEGIN, END = "# ---- ART (generated by docs/plans/bonanza-courses/first/decals.py) ----", "# ---- end ART ----"
K, C, M, W = 0, 1, 2, 3

# ---- the geometry the art stands on (course coordinates: the sketch's + 4) ----
Z = 26
# the FRAME before the leap: the run-up's last rail blocks (x 48, y 46 and 50), raised into pillars
RUNUP_X = 48                                           # its last tile before the gap (sketch 44)
RUN_Z = lambda x: (Z - 17.5) - 2.0 * (x - 45) / 4.0    # the run-up ramp: x 45 -> 49, Z-17.5 -> Z-19.5
FRAME_FLOOR = RUN_Z(RUNUP_X + 0.5)                     # the floor under the banner's middle
FRAME_TOP = 13.0                                       # the pillars' tops, units (about 6 over the floor)
FRAME_BAN = (FRAME_FLOOR + 4.0, FRAME_FLOOR + 5.5)     # the banner: 4 units clear over the floor, 1.5 deep
FRAME_Y = (46, 51)                                     # the pillars' cells: y 46 (back) and y 50 (front)
# the LONE pillars in the void, each a floating tile with a pennant
LONE = [(31, 39, 15.0), (51, 43, 9.0)]                 # (wx, wy, top z)
START = (9, 9, Z)                                      # the start cell and its height
LIP = (24, 27, 24, 28, Z - 6, Z - 8)                   # the lip ramp: x 24 - 27, y 24 - 28, z 20 -> 18 (+y)


# (revision 9: the FRAME and its banner are gone - the owner: "The ball rolls in front of the arch, because
# its just art ... But we have an actual arch, as a prop, we can use" - the sketch lays an ARCHWAY instead)

# the owner's own pixels on the chevrons (2026-11-18, read off their edit of the preview): black, in picture
# coordinates - three where the tile under the leading arm showed through, one to even the forward arrow
CHEV_TOUCH = [(251, 401), (250, 402), (249, 403), (232, 415)]


def geometry_lines():
    L = ["# LONE pillars in the void, away from the path, each topped by a pennant"]
    for x, y, z in LONE:
        L += ["floor tile %d %d  flat %g" % (x, y, z), "float tile %d %d" % (x, y)]
    return L


# ---- rasterising ---------------------------------------------------------------
class Art:
    """pixels (picture px) -> colour, with an outline pass; `host`: the cells a decal may be painted on -
    a pixel whose VISIBLE surface (the canvas's owner, the tile that drew it last) is another cell is left
    alone, so a decal never paints over a rail or anything else standing in front of its floor"""

    def __init__(self, host=None):
        self.px = {}
        self.host = host

    def outline(self, inside, colour, box):
        """fill the pixels whose centre `inside` accepts with colour, and every filled pixel with a
        4-neighbour outside the shape black: a one-pixel line, the game's"""
        x0, y0, x1, y1 = box
        got = {(x, y) for y in range(y0, y1) for x in range(x0, x1) if inside(x + 0.5, y + 0.5)
               and (self.host is None or owner_at(x, y) in self.host)}
        for (x, y) in got:
            edge = any((x + dx, y + dy) not in got for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))
            self.px[(x, y)] = K if edge else colour(x, y)

    def write(self, path, note):
        xs = [p[0] for p in self.px]
        ys = [p[1] for p in self.px]
        ax, ay = min(xs), min(ys)
        rows = ["".join(str(self.px[(x, y)]) if (x, y) in self.px else "." for x in range(ax, max(xs) + 1))
                for y in range(ay, max(ys) + 1)]
        with open(path, "w", encoding="ascii", newline="\n") as f:
            f.write("# %s\n# GENERATED by docs/plans/bonanza-courses/first/decals.py - edit that, not this\n" % note)
            f.write("\n".join(rows) + "\n")
        return ax, ay


CANVAS = []


def owner_at(x, y):
    """the cell that drew picture pixel (x, y) last, from the course's own render (None: nothing)"""
    cv = CANVAS[-1]
    if not (0 <= y < cv.h and 0 <= x < cv.w):
        return None
    v = cv.obuf[y][x]
    return None if v < 0 else (v >> 8, v & 255)


def capture_render():
    """compile through a render that keeps every pixel's owner (Canvas.obuf), and keep the picture's canvas"""
    orig = B.render

    def rec(tiles, ops, x0, y0, w, h, owners=False):
        cv = orig(tiles, ops, x0, y0, w, h, True)
        CANVAS.append(cv)
        return cv
    B.render = rec


def floor_point(c, X, Y, z):
    return 16 * (X - Y) + c.x0, 8 * (X + Y) - 8 * z + c.y0


def unproject_floor(c, sx, sy, zf):
    """a picture pixel's floor point (X, Y) on a floor whose height is zf(X, Y) (two refinements)"""
    z = zf(None, None)
    for _ in range(3):
        u = (sx - c.x0) / 16.0
        v = (sy - c.y0 + 8 * z) / 8.0
        X, Y = (u + v) / 2, (v - u) / 2
        z = zf(X, Y)
    return X, Y


def tee(c):
    """the start's TEE: a magenta disc (radius 0.62 tiles) with a black rim and a white highlight crescent
    at its back-left, on the start cell's centre"""
    a = Art()
    wx, wy, z = START
    cx, cy = wx + 0.5, wy + 0.5
    zf = lambda X, Y: z
    r = 0.62
    px, py = floor_point(c, cx, cy, z)

    def inside(sx, sy):
        X, Y = unproject_floor(c, sx, sy, zf)
        return (X - cx) ** 2 + (Y - cy) ** 2 <= r * r

    def colour(sx, sy):
        X, Y = unproject_floor(c, sx, sy, zf)
        d = math.hypot(X - cx, Y - cy)
        back = (X - cx) + (Y - cy) < -0.25            # its back half, toward the light (upper left)
        return W if (r - 0.2 < d <= r - 0.08 and back) else M
    a.outline(inside, colour, (int(px - 20), int(py - 12), int(px + 21), int(py + 13)))
    return a


def chevrons(c):
    """two chevrons down the lip's ramp, pointing downhill (+y): magenta, black-lined"""
    x0, x1, y0, y1, za, zb = LIP
    a = Art(host={(x, y) for x in range(x0, x1) for y in range(y0, y1)})
    zf = lambda X, Y: za if Y is None else za + (zb - za) * min(1, max(0, (Y - y0) / (y1 - y0)))
    cx = (x0 + x1) / 2.0
    tips = (25.55, 26.75)                                # each chevron's tip, y
    half, thick, depth = 0.95, 0.30, 0.55                # its arms' reach across, their thickness, the V's depth

    def inside(sx, sy):
        X, Y = unproject_floor(c, sx, sy, zf)
        dx = abs(X - cx)
        if dx > half:
            return False
        for ty in tips:
            back = ty - depth * dx / half           # the arm's leading edge: the tip at the centre, back at the ends
            if back - thick <= Y <= back:
                return True
        return False
    lx, ly = floor_point(c, cx - 1.2, y0, za)
    rx, ry = floor_point(c, cx + 1.2, y1, zb)
    a.outline(inside, lambda sx, sy: M, (int(min(lx, rx)) - 30, int(min(ly, ry)) - 30,
                                         int(max(lx, rx)) + 30, int(max(ly, ry)) + 30))
    for p in CHEV_TOUCH:                               # the owner's pixels
        a.px[p] = K
    return a


def banner(c):
    """the FRAME's banner: an upright cloth on the plane x = RUNUP_X + 0.5 between the pillars, magenta with
    white trim along its top and foot and three white studs, black-lined"""
    a = Art()
    X0 = RUNUP_X + 0.5
    ya, yb = FRAME_Y[0] + 1.0, FRAME_Y[1] - 1.0          # between the pillars' faces
    za, zb = FRAME_BAN

    def plane(sx, sy):
        Y = X0 - (sx - c.x0) / 16.0
        z = (8 * (X0 + Y) + c.y0 - sy) / 8.0
        return Y, z

    def inside(sx, sy):
        Y, z = plane(sx, sy)
        return ya <= Y <= yb and za <= z <= zb

    def colour(sx, sy):
        Y, z = plane(sx, sy)
        if z > zb - 0.28 or z < za + 0.28:
            return W                                     # the trim
        mid = (za + zb) / 2
        for k in range(3):
            sy_ = ya + (yb - ya) * (k + 0.5) / 3
            if abs(Y - sy_) + abs(z - mid) * 0.6 < 0.17:
                return W                                 # a stud
        return M
    p1 = floor_point(c, X0, ya, zb)
    p2 = floor_point(c, X0, yb, za)
    a.outline(inside, colour, (int(min(p1[0], p2[0])) - 4, int(min(p1[1], p2[1])) - 4,
                               int(max(p1[0], p2[0])) + 5, int(max(p1[1], p2[1])) + 5))
    return a


def pennant(c, wx, wy, z):
    """a lone pillar's PENNANT, the checkpoint flag's kind: a black pole from the tile's centre, a magenta
    pennant to its right with a white stripe, black-lined"""
    a = Art()
    bx, by = floor_point(c, wx + 0.5, wy + 0.5, z)
    bx, by = int(bx), int(by)
    for y in range(by - 22, by + 1):
        a.px[(bx, y)] = K                              # the pole
    a.px[(bx - 1, by - 22)] = K
    a.px[(bx + 1, by - 22)] = K                        # its knob

    def inside(sx, sy):
        x, y = sx - (bx + 1), sy - (by - 21)
        return 0 <= x <= 11 and abs(y - 4) <= 4 - x * 4.0 / 11.0 + 0.5

    def colour(sx, sy):
        y = sy - (by - 21)
        return W if 3.2 <= y <= 4.8 else M
    a.outline(inside, colour, (bx + 1, by - 22, bx + 14, by - 11))
    return a


def main():
    with open(COURSE, encoding="ascii") as f:
        src = f.read()
    src = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", "", src, flags=re.S).rstrip("\n") + "\n"
    geo = "\n".join([BEGIN] + geometry_lines()) + "\n"
    capture_render()
    c = B.compile_course(src + geo, COURSE)
    CANVAS[:] = [cv for cv in CANVAS if cv.w == 8 * c.cols][-1:]      # the picture's own canvas
    pieces = [("tee", tee(c), "the start's TEE: a magenta disc, black rim, white highlight"),
              ("chev", chevrons(c), "two CHEVRONS down the lip's ramp, pointing downhill")]
    for i, (x, y, z) in enumerate(LONE):
        pieces.append(("pen%d" % i, pennant(c, x, y, z), "a lone pillar's PENNANT"))
    lines = []
    for name, art, note in pieces:
        fn = "roll_%s.bba" % name
        ax, ay = art.write(os.path.join(CDIR, fn), note)
        lines.append("art %s %d %d" % (fn, ax, ay))
    out = src + geo + "\n".join(lines) + "\n" + END + "\n"
    with open(COURSE, "w", encoding="ascii", newline="\n") as f:
        f.write(out)
    print("decals: %d pieces into %s" % (len(pieces), os.path.relpath(COURSE, ROOT)))


if __name__ == "__main__":
    main()
