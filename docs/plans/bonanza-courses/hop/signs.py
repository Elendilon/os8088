"""ISLAND HOP's SIGNS (the owner, 2026-11-19: "paste on some art 'signs' telling
them 'Jump!' and 'Jump Twice!'").

Host-only and deterministic, nothing in `make` runs it: the artwork's SOURCE
(CLAUDE.md, "treat artwork as source"), FIRST ROLL's decals.py's way and its
machinery (the owner buffer, the projection, the one-pixel black line). Each
sign is a board on a post standing on a back-rail block beside the path, the
pin clock's kind (a plate on a pole: "somewhat fits the art"): a white board
(colour 3) with a magenta border (2) and black lettering in the tree's 8 x 8
face (fonts/tallx.f8, the tool's label_glyph), its post banded black and
white. Art takes the occlusion of the surface beneath it (SPEC.md 130.23.2).

    python3 docs/plans/bonanza-courses/hop/sketch.py --bbc apps/bonanza/courses/hop.bbc --force
    python3 docs/plans/bonanza-courses/hop/signs.py

writes apps/bonanza/courses/hop_sign*.bba and the block between the ART
markers at the end of apps/bonanza/courses/hop.bbc."""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, os.path.join(HERE, "..", "first"))
import bbcourse as B                                   # noqa: E402
import decals as D                                     # noqa: E402  (FIRST ROLL's: Art, the owner buffer)
import importlib.util                                  # noqa: E402
_spec = importlib.util.spec_from_file_location("hop_sketch", os.path.join(HERE, "sketch.py"))
S = importlib.util.module_from_spec(_spec)             # the layout (SIGNS, OFF), by path: first/ has a sketch too
_spec.loader.exec_module(S)

COURSE = os.path.join(ROOT, "apps", "bonanza", "courses", "hop.bbc")
CDIR = os.path.dirname(COURSE)
BEGIN, END = "# ---- ART (generated by docs/plans/bonanza-courses/hop/signs.py) ----", "# ---- end ART ----"
K, C, M, W = 0, 1, 2, 3
POST = 9                                               # px of post between the block's top and the board


def rail_top(wx, wy):
    """the height of the rail block a sign stands on: its line in hop.bbc"""
    with open(COURSE, encoding="ascii") as f:
        for ln in f:
            m = re.match(r"wall\s+tile\s+(-?\d+)\s+(-?\d+)\s+flat\s+([\d.]+)", ln)
            if m and (int(m.group(1)), int(m.group(2))) == (wx, wy):
                return float(m.group(3))
    raise SystemExit("signs.py: no rail block at (%d, %d) in hop.bbc" % (wx, wy))


def sign(c, sx, sy, words):
    """a board on a post over the block (sx, sy) (world cell), the words in lines"""
    a = D.Art()
    z = rail_top(sx, sy)
    bx, by = D.floor_point(c, sx + 0.5, sy + 0.5, z)
    bx, by = int(bx), int(by)
    lines = words.split("\n")
    tw = max(len(t) for t in lines) * 8
    w, h = tw + 6, 8 * len(lines) + 1 + 6           # 2 border + 1 margin each side
    x0, y1 = bx - w // 2, by - POST                 # the board's left, its bottom row + 1
    y0 = y1 - h
    for y in range(y1, by + 1):                     # the POST, banded
        for dx in (-1, 0):
            a.px[(bx + dx, y)] = K if dx == -1 or (y - y1) % 4 < 2 else W
    for y in range(y0, y1):                         # the BOARD: a black line, a magenta border, white
        for x in range(x0, x0 + w):
            edge = x in (x0, x0 + w - 1) or y in (y0, y1 - 1)
            ring = x in (x0 + 1, x0 + w - 2) or y in (y0 + 1, y1 - 2)
            a.px[(x, y)] = K if edge else M if ring else W
    for r, t in enumerate(lines):                   # the WORDS, centred, black
        tx = x0 + 3 + (tw - 8 * len(t)) // 2
        for i, ch in enumerate(t):
            for (gx, gy), _ in B.label_glyph(ch, 0, 0, K).items():
                a.px[(tx + 8 * i + gx, y0 + 3 + 8 * r + gy)] = K
    return a


def main():
    with open(COURSE, encoding="ascii") as f:
        src = f.read()
    src = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", "", src, flags=re.S).rstrip("\n") + "\n"
    D.capture_render()
    c = B.compile_course(src, COURSE)
    D.CANVAS[:] = [cv for cv in D.CANVAS if cv.w == 8 * c.cols][-1:]
    lines = []
    for i, (x, y, words) in enumerate(S.SIGNS):
        art = sign(c, int(x) + S.OFF, int(y) + S.OFF, words)
        fn = "hop_sign%d.bba" % i
        ax, ay = art.write(os.path.join(CDIR, fn), "a SIGN: %s" % words.replace("\n", " "))
        with open(os.path.join(CDIR, fn), encoding="ascii") as f:
            body = f.read().replace("first/decals.py", "hop/signs.py")
        with open(os.path.join(CDIR, fn), "w", encoding="ascii", newline="\n") as f:
            f.write(body)
        lines.append("art %s %d %d" % (fn, ax, ay))
    with open(COURSE, "w", encoding="ascii", newline="\n") as f:
        f.write(src + "\n".join([BEGIN] + lines) + "\n" + END + "\n")
    print("signs: %d into %s" % (len(lines), os.path.relpath(COURSE, ROOT)))


if __name__ == "__main__":
    main()
