def wall_top(wx, wy):
    return SG.rail_top(wx, wy)


def text_px(lines, ink=K):
    """the words in the tree's 8 x 8 face, each line centred: -> ({(x, y): ink}, width, height); the glyphs'
    blank top row and bottom row are trimmed, so a line is 6 px and lines are 8 apart"""
    tw = max(len(t) for t in lines) * 8 - 1
    out = {}
    for r, t in enumerate(lines):
        x0 = (tw - (8 * len(t) - 1)) // 2
        for i, ch in enumerate(t):
            for (gx, gy), _ in B.label_glyph(ch, 0, 0, ink).items():
                out[(x0 + 8 * i + gx, 8 * r + gy - 1)] = ink
    return out, tw, 8 * len(lines) - 2


def shape(px, inside, w, h, fill):
    """fill every (x, y) of the w x h box that `inside` accepts with fill(x, y), and the shape's edge black"""
    got = {(x, y) for y in range(h) for x in range(w) if inside(x, y)}
    for (x, y) in got:
        edge = any((x + dx, y + dy) not in got for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))
        px[(x, y)] = K if edge else fill(x, y)
    return got


def plate(words=None, icon=None):
    """the HANGING PLATE: a rounded slab, black-lined, a red ring round a yellow face, the words (or an icon,
    a {(x, y): colour} with its size) black on it.  -> ({(x, y): colour}, w, h)"""
    if icon is not None:
        ink, tw, th = icon
    else:
        ink, tw, th = text_px(words.split("\n"))
    w, h = tw + 8, th + 8                          # line, ring, 2 margin each side
    rr = 2                                         # the corners' cut

    def inside(x, y):
        cx = min(x, w - 1 - x)
        cy = min(y, h - 1 - y)
        return not (cx + cy < rr)

    def fill(x, y):
        return R if (x in (1, w - 2) or y in (1, h - 2) or min(x, w - 1 - x) + min(y, h - 1 - y) <= rr) else Y
    px = {}
    shape(px, inside, w, h, fill)
    for (x, y), v in ink.items():
        px[(x + 4, y + 4)] = v
    return px, w, h


def hang_sign(c, sx, sy, words=None, icon=None):
    """a plate HANGING from a gallows: a post up from the rail block's top, an arm out to the LEFT (the way
    the ball travels, -x), two chains, the plate under the arm"""
    a = D.Art()
    bx, by = D.floor_point(c, sx + 0.5, sy + 0.5, wall_top(sx, sy))
    bx, by = int(bx), int(by)
    pp, w, h = plate(words, icon)
    gap = 3                                        # chain length
    arm_y = by - 8 - h - gap - 3                   # the arm's top row: the plate clears the block by 8 px
    right = bx + 2
    left = bx - w - 3
    for y in range(arm_y, by + 1):                 # the post: black, red, black
        for dx, v in ((-1, K), (0, R), (1, K)):
            a.px[(bx + dx, y)] = v
    a.px[(bx, arm_y)] = K
    for x in range(left, right):                   # the arm: black, red, black; a knob at its end
        a.px[(x, arm_y)] = K
        a.px[(x, arm_y + 1)] = R if left < x < bx - 1 else K
        a.px[(x, arm_y + 2)] = K
    a.px[(left, arm_y + 1)] = K
    for k in range(1, 4):                          # a brace under the arm's root
        a.px[(bx - 1 - k, arm_y + 2 + k)] = K
    px0 = left + 1 + (bx - 3 - left - w) // 2      # the plate centred under the arm's free span
    py0 = arm_y + 3 + gap
    for cx in (px0 + 4, px0 + w - 5):              # the chains: a link a pixel, gaps between
        for y in range(arm_y + 3, py0):
            if (y - arm_y) % 2 == 1:
                a.px[(cx, y)] = K
    for (x, y), v in pp.items():
        a.px[(px0 + x, py0 + y)] = v
    return a


def banner_sign(c, sx, sy, words):
    """a CLOTH between two posts in the plane of the rail (y = sy + 0.5, along x): it recedes with the rail,
    so it is sheared one row down for every two columns to the right, words and all"""
    a = D.Art()
    ink, tw, th = text_px(words.split("\n"))
    w, h = tw + 8, th + 8
    px = {}

    def inside(x, y):
        return True

    def fill(x, y):
        return R if (x in (1, w - 2) or y in (1, h - 2)) else Y
    shape(px, inside, w, h, fill)
    tabs = {}                                      # a scalloped hem: red tabs, black-lined, under the cloth
    for x in range(2, w - 2):
        if (x // 4) % 2 == 0:
            tabs[(x, h)] = R if (x % 4) in (1, 2) else K
            tabs[(x, h + 1)] = K if (x % 4) in (1, 2) else None
    px.update({k: v for k, v in tabs.items() if v is not None})
    for (x, y), v in ink.items():
        px[(x + 4, y + 4)] = v
    X0 = sx + 0.5                                  # the cloth's middle over the sign's block
    Yp = sy + 0.5
    mx, my = D.floor_point(c, X0, Yp, wall_top(sx, sy))
    ox = int(mx) - w // 2                          # the cloth's left column
    oy = int(my) - 10 - h - w // 4                 # its top-left row (the middle column clears the block)
    for (x, y), v in px.items():
        a.px[(ox + x, oy + y + x // 2)] = v
    for side, x in (("l", -2), ("r", w + 1)):      # the posts: from the cloth's top to the rail block below
        Xp = X0 + (ox + x + 0.5 - mx) / 16.0
        cell = int(math.floor(Xp))
        try:
            zt = wall_top(cell, sy)
        except SystemExit:
            zt = wall_top(sx, sy)
        _, foot = D.floor_point(c, Xp, Yp, zt)
        top = oy - 2 + x // 2
        for y in range(top, int(foot) + 1):
            a.px[(ox + x, y)] = R
            a.px[(ox + x - 1, y)] = K
            a.px[(ox + x + 1, y)] = K
        a.px[(ox + x, top - 1)] = K
        a.px[(ox + x, top)] = Y                    # a yellow cap
    return a


# ---- the icons: a side view, the ball on the right travelling left onto a step -----------------------
def icon(twice):
    """a side view, 36 x 18: the ball at the right, its path a solid black arc onto a red step at the left (the
    way the ball travels on screen).  "JUMP TWICE!": a taller step, the path bouncing once IN THE AIR, a red
    burst where the second press is"""
    px = {}
    w, h = 36, 18
    gy = h - 1                                     # the ground line
    step_w, step_h = 10, (5 if not twice else 9)
    for x in range(w):
        px[(x, gy)] = K
    for y in range(gy - step_h, gy):               # the STEP: red, black-lined, a green top
        for x in range(0, step_w):
            px[(x, y)] = K if (y == gy - step_h or x == step_w - 1) else (G if y == gy - step_h + 1 else R)
    bx, by = w - 5, gy - 3                         # the BALL: a black-lined green disc
    for y in range(by - 3, by + 4):
        for x in range(bx - 3, bx + 4):
            d = (x - bx) ** 2 + (y - by) ** 2
            if d <= 10:
                px[(x, y)] = K if d >= 5 else G
    px[(bx - 1, by - 1)] = Y                       # its glint

    def arc(p0, p1, peak):
        n = int(abs(p1[0] - p0[0]) * 2) + 2
        last = None
        for i in range(n + 1):
            t = i / float(n)
            x = p0[0] + (p1[0] - p0[0]) * t
            y = p0[1] + (p1[1] - p0[1]) * t - peak * 4 * t * (1 - t)
            q = (int(round(x)), int(round(y)))
            if q != last and q not in px:
                px[q] = K
            last = q
    land = (step_w // 2, gy - step_h - 2)
    if not twice:
        arc((bx - 2, by - 4), land, 8)
    else:
        mid = (step_w + (bx - step_w) // 2 - 1, 5)
        arc((bx - 2, by - 4), mid, 4)
        arc(mid, land, 4)
        for dx, dy in ((0, -2), (-2, 0), (2, 0), (-1, -1), (1, -1)):   # the burst: the "and again" press
            px[(mid[0] + dx, mid[1] + dy)] = R
    return px, w, h


# ---- the floor paint ------------------------------------------------------------------------------
def floor_words(c, flr, words, scale, axis):
    """the words PAINTED on a floor (x0 y0 x1 y1 z) as a road marking: a red panel, black-lined, the letters
    yellow in it, centred.  axis "x": reading along +x (down the screen to the right), the letters' tops toward
    -y; axis "y": reading along -y (up to the right), the tops toward -x.  A glyph pixel is 1/scale of a tile;
    the strokes are thickened a row down so they survive the floor's squash"""
    x0, y0, x1, y1, z = flr
    a = D.Art(host={(x, y) for x in range(x0, x1) for y in range(y0, y1)})
    ink, tw, th = text_px(words.split("\n"))
    fat = set()
    for (x, y) in ink:
        fat.add((x, y))
        fat.add((x, y + 1))
    th += 1
    m = 3                                          # the panel's margin round the words, glyph pixels
    cx, cy = (x0 + x1) / 2.0, (y0 + y1) / 2.0
    zf = lambda X, Y: z

    def glyph(sx, sy):
        X, Y = D.unproject_floor(c, sx, sy, zf)
        if axis == "x":
            u, v = (X - cx) * scale + tw / 2.0, (Y - cy) * scale + th / 2.0
        else:
            u, v = (cy - Y) * scale + tw / 2.0, (X - cx) * scale + th / 2.0
        return int(math.floor(u)), int(math.floor(v))

    def inside(sx, sy):
        u, v = glyph(sx, sy)
        return -m <= u < tw + m and -m <= v < th + m

    def colour(sx, sy):
        return YEL if glyph(sx, sy) in fat else R
    pts = [D.floor_point(c, X, Yy, z) for X in (x0, x1) for Yy in (y0, y1)]
    xs = [p[0] for p in pts]
    ys = [p[1] for p in pts]
    a.outline(inside, colour, (int(min(xs)), int(min(ys)), int(max(xs)) + 1, int(max(ys)) + 1))
    return a


# ---- the interest pieces -------------------------------------------------------------------------
def tee(c):
    """the start's TEE (FIRST ROLL's): a red disc of radius 0.62 tiles, black rim, a yellow highlight crescent
    on its back half"""
    a = D.Art()
    wx, wy, z = START
    cx, cy = wx + 0.5, wy + 0.5
    zf = lambda X, Y: z
    r = 0.62
    px, py = D.floor_point(c, cx, cy, z)

    def inside(sx, sy):
        X, Y = D.unproject_floor(c, sx, sy, zf)
        return (X - cx) ** 2 + (Y - cy) ** 2 <= r * r

    def colour(sx, sy):
        X, Y = D.unproject_floor(c, sx, sy, zf)
        d = math.hypot(X - cx, Y - cy)
        back = (X - cx) + (Y - cy) < -0.25
        return YEL if (r - 0.2 < d <= r - 0.08 and back) else R
    a.outline(inside, colour, (int(px - 20), int(py - 12), int(px + 21), int(py + 13)))
    return a


def chevrons(c):
    """two CHEVRONS down the lip ramp R, pointing downhill (+y): red, black-lined (FIRST ROLL's, re-sized for a
    ramp two tiles long)"""
    x0, x1, y0, y1, za, zb = LIP
    a = D.Art(host={(x, y) for x in range(x0, x1) for y in range(y0, y1)})
    zf = lambda X, Y: za if Y is None else za + (zb - za) * min(1, max(0, (Y - y0) / float(y1 - y0)))
    cx = (x0 + x1) / 2.0
    tips = (y0 + 0.95, y0 + 1.75)
    half, thick, depth = 1.05, 0.28, 0.5

    def inside(sx, sy):
        X, Y = D.unproject_floor(c, sx, sy, zf)
        dx = abs(X - cx)
        if dx > half:
            return False
        for ty in tips:
            back = ty - depth * dx / half
            if back - thick <= Y <= back:
                return True
        return False
    lx, ly = D.floor_point(c, cx - 1.6, y0, za)
    rx, ry = D.floor_point(c, cx + 1.6, y1, zb)
    a.outline(inside, lambda sx, sy: R, (int(min(lx, rx)) - 30, int(min(ly, ry)) - 30,
                                         int(max(lx, rx)) + 30, int(max(ly, ry)) + 30))
    return a


def pennant(c, wx, wy, z, tall=22):
    """a PENNANT, the checkpoint flag's kind (FIRST ROLL's): a black pole from the tile's centre, a red pennant
    with a yellow stripe, black-lined"""
    a = D.Art()
    bx, by = D.floor_point(c, wx + 0.5, wy + 0.5, z)
    bx, by = int(bx), int(by)
    for y in range(by - tall, by + 1):             # the pole: yellow between black lines (a black pole alone is
        a.px[(bx - 1, y)] = K                      # invisible against the void: Little Hop is on black)
        a.px[(bx, y)] = Y
    a.px[(bx, by - tall - 1)] = K
    a.px[(bx - 1, by - tall - 1)] = K

    def inside(sx, sy):
        x, y = sx - (bx + 1), sy - (by - tall + 1)
        return 0 <= x <= 11 and abs(y - 4) <= 4 - x * 4.0 / 11.0 + 0.5

    def colour(sx, sy):
        y = sy - (by - tall + 1)
        return Y if 3.2 <= y <= 4.8 else R
    a.outline(inside, colour, (bx + 1, by - tall, bx + 14, by - tall + 11))
    return a


