# ---- assembling a variant ------------------------------------------------------------------------
_CAPTURED = []
_OWNERS = {}


def owners(text, path):
    """compile the course's geometry and keep the canvas that says which cell drew each pixel (decals'
    owner buffer) - per geometry, since a second compile of the same text comes from the tool's cache"""
    if not _CAPTURED:
        D.capture_render()
        _CAPTURED.append(1)
    D.CANVAS[:] = []
    c = B.compile_course(text, path)
    cvs = [cv for cv in D.CANVAS if cv.w == 8 * c.cols]
    if cvs:
        _OWNERS[text] = cvs[-1]
    D.CANVAS[:] = [_OWNERS[text]]
    return c


def build(signs, extras, outdir, prefix="hop_"):
    """write outdir/hop.bbc and its .bba files (named PREFIX...): the course with THIS ART block; -> the course's
    path.  The compiler finds a `.bba` in apps/bonanza/courses/ only, whatever the course's own folder, so a
    scratch variant takes a prefix of its own (measure() points the compiler at its folder; sheet() copies its
    files in for the tool's run and takes them out again)"""
    with open(COURSE, encoding="ascii") as f:
        src = f.read()
    src = OLD.sub("", src).rstrip("\n") + "\n"
    geo = [BEGIN]
    if "pillar" in extras:
        geo += pillar_lines()
    geo_txt = "\n".join(geo) + "\n"
    path = os.path.join(outdir, "hop.bbc")
    c = owners(src + geo_txt, path)
    pieces = []
    for i, (x, y, words) in enumerate(S.SIGNS):
        sx, sy = int(x) + S.OFF, int(y) + S.OFF
        one = words.replace("\n", " ")
        if signs == "board":
            art = SG.sign(c, sx, sy, words)
        elif signs == "hang":
            art = hang_sign(c, sx, sy, words)
        elif signs == "banner":
            art = banner_sign(c, sx, sy, words)
        elif signs == "icon":
            art = hang_sign(c, sx, sy, icon=icon(i == 1))
        elif signs == "floor":
            art = (floor_words(c, T1, "JUMP!", 10, "y") if i == 0
                   else floor_words(c, U1, "JUMP\nTWICE!", 10, "x"))
        else:
            continue
        pieces.append((prefix + "sign%d" % i, art, "a SIGN (%s): %s" % (signs, one)))
    if "tee" in extras:
        pieces.append((prefix + "tee", tee(c), "the start's TEE: a red disc, black rim, yellow highlight"))
    if "chev" in extras:
        pieces.append((prefix + "chev", chevrons(c), "two CHEVRONS down the lip ramp R, pointing downhill"))
    if "goal" in extras:
        for k, (x, y) in enumerate(GOAL_PENS):
            pieces.append((prefix + "goal%d" % k, pennant(c, x, y, wall_top(x, y), 28), "a PENNANT on the goal's back rail"))
    if "tufts" in extras:
        pieces.append((prefix + "tufts", tufts(c), "grass TUFTS with a flower on rail tops"))
    if "pillar" in extras:
        x, y, z = PILLAR
        pieces.append((prefix + "pillar", pennant(c, x, y, z), "the lone pillar's PENNANT"))
    lines = []
    for name, art, note in pieces:
        fn = name + ".bba"
        ax, ay = art.write(os.path.join(outdir, fn), note)
        with open(os.path.join(outdir, fn), encoding="ascii") as f:
            body = f.read().replace("first/decals.py", "hop/art.py")
        with open(os.path.join(outdir, fn), "w", encoding="ascii", newline="\n") as f:
            f.write(body)
        lines.append("art %s %d %d" % (fn, ax, ay))
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write(src + geo_txt + "\n".join(lines) + ("\n" if lines else "") + END + "\n")
    return path


# ---- the comparison sheet ------------------------------------------------------------------------
def measure(path):
    keep = B.COURSE_DIR
    B.COURSE_DIR = os.path.dirname(os.path.abspath(path))
    try:
        with open(path, encoding="ascii") as f:
            c = B.compile_course(f.read() + "# measured in %s\n" % B.COURSE_DIR, path)
    finally:
        B.COURSE_DIR = keep
    st = [c.stored] + ([c.wstored] if c.split else [])
    return c, {"stored": sum(len(s) for s in st), "lz4": sum(B.packed_len(s, "lz4") for s in st),
               "lzb": sum(B.packed_len(s, "lzb") for s in st), "blocks": len(c.blocks), "records": len(c.records)}


def pictures(c, Image):
    cga = Image.new("RGB", (c.width, c.lines))
    cga.putdata([P0[v] for r in c.pic for v in r])
    h = Image.new("L", (c.width * 2, c.lines))
    data = []
    for y, row in enumerate(c.pic):
        for x, v in enumerate(row):
            pr = B.herc_pair(v, y, x)
            data += [255 * (pr >> 1), 255 * (pr & 1)]
    h.putdata(data)
    return cga, h.convert("RGB")


ZOOM = 4
CROPS = {"JUMP!": (764, 108, 924, 248), "JUMP TWICE!": (552, 108, 712, 248),
         "tee": (830, 176, 940, 256), "chev": (220, 100, 350, 200), "goal": (430, 260, 570, 390),
         "tufts": (480, 60, 1010, 330), "pillar": (120, 70, 240, 170)}


def crop_pair(cga, herc, box, Image, zoom=ZOOM):
    x0, y0, x1, y1 = box
    a = cga.crop(box).resize(((x1 - x0) * zoom, (y1 - y0) * zoom), Image.NEAREST)
    b = herc.crop((2 * x0, y0, 2 * x1, y1)).resize(((x1 - x0) * zoom, (y1 - y0) * zoom), Image.NEAREST)
    return a, b


def label(img, text, ImageDraw, at=(6, 4)):
    d = ImageDraw.Draw(img)
    for dx, dy in ((1, 1), (-1, -1), (1, -1), (-1, 1)):
        d.text((at[0] + dx, at[1] + dy), text, fill=(0, 0, 0))
    d.text(at, text, fill=(255, 255, 255))


def grid(rows, Image, ImageDraw, title, head):
    """rows: [(label, [image, ...])] -> one sheet, a title and a heading row"""
    pad, top = 8, 44
    cw = [max(r[1][k].width for r in rows) for k in range(len(rows[0][1]))]
    rh = [max(im.height for im in r[1]) + 22 for r in rows]
    W = sum(cw) + pad * (len(cw) + 1)
    H = top + sum(rh) + pad * (len(rows) + 1)
    sheet = Image.new("RGB", (W, H), (40, 40, 48))
    d = ImageDraw.Draw(sheet)
    d.text((pad, 6), title, fill=(255, 255, 255))
    x = pad
    for k, t in enumerate(head):
        d.text((x, 26), t, fill=(200, 200, 200))
        x += cw[k] + pad
    y = top + pad
    for (lab, ims), h in zip(rows, rh):
        d.text((pad, y), lab, fill=(255, 255, 160))
        x = pad
        for k, im in enumerate(ims):
            sheet.paste(im, (x, y + 18))
            x += cw[k] + pad
        y += h + pad
    return sheet


def sheet(out):
    from PIL import Image, ImageDraw
    import subprocess
    os.makedirs(out, exist_ok=True)
    variants = [("signs-" + s, s, ()) for s in SIGN_STYLES] + [("extra-" + e, "board", (e,)) for e in EXTRAS] + \
               [("set-all-extras", "board", EXTRAS), ("set-pick", "hang", ("tee", "chev", "goal", "pillar"))]
    res = {}
    for name, sg, ex in variants:
        d = os.path.join(out, name)
        os.makedirs(d, exist_ok=True)
        for fn in os.listdir(d):
            if fn.endswith(".bba"):
                os.remove(os.path.join(d, fn))
        pre = "hx_" + re.sub(r"[^a-z0-9]", "", name) + "_"
        p = build(sg, ex, d, pre)
        mine = [fn for fn in os.listdir(d) if fn.startswith(pre) and fn.endswith(".bba")]
        for fn in mine:                            # the tool's own run, as written: its .bba files beside the courses
            with open(os.path.join(d, fn), "rb") as f_, open(os.path.join(CDIR, fn), "wb") as g_:
                g_.write(f_.read())
        try:
            r = subprocess.run([sys.executable, os.path.join(ROOT, "tools", "bbcourse.py"), p, "--png", d],
                               capture_output=True, text=True)
        finally:
            for fn in mine:
                os.remove(os.path.join(CDIR, fn))
        ok = r.returncode == 0
        c, m = measure(p)
        m["ok"] = ok
        res[name] = (c, m)
        print("%-18s compile %s  stored %6d  LZB %5d  LZ4 %5d  blocks %4d  records %4d%s" % (
            name, "ok" if ok else "FAILED", m["stored"], m["lzb"], m["lz4"], m["blocks"], m["records"],
            "" if ok else "\n" + (r.stderr or r.stdout)[-600:]))
    base = res["signs-none"][1]
    pics = {n: pictures(c, Image) for n, (c, m) in res.items()}

    def cost(n, ref="signs-none"):
        m, b = res[n][1], res[ref][1]
        return "LZB %+d, LZ4 %+d, stored %+d, blocks %+d" % (m["lzb"] - b["lzb"], m["lz4"] - b["lz4"],
                                                            m["stored"] - b["stored"], m["blocks"] - b["blocks"])
    rows = []
    for s in SIGN_STYLES:
        if s == "none":
            continue
        n = "signs-" + s
        ims = []
        for w in ("JUMP!", "JUMP TWICE!"):
            ims += crop_pair(pics[n][0], pics[n][1], CROPS[w], Image)
        rows.append(("%s   (both signs: %s against no signs)" % (s.upper(), cost(n)), ims))
    grid(rows, Image, ImageDraw, "LITTLE HOP - sign options, palette 0 (CGA: green, red, yellow on black) and "
         "Hercules; x%d" % ZOOM, ["JUMP!  CGA", "JUMP!  Hercules", "JUMP TWICE!  CGA", "JUMP TWICE!  Hercules"]
         ).save(os.path.join(out, "signs-sheet.png"))
    rows = []
    for e in EXTRAS:
        n = "extra-" + e
        z = 2 if e == "tufts" else ZOOM
        ims = list(crop_pair(pics[n][0], pics[n][1], CROPS[e], Image, z))
        before = crop_pair(pics["signs-board"][0], pics["signs-board"][1], CROPS[e], Image, z)[0]
        rows.append(("%s   (%s against today's course)" % (e.upper(), cost(n, "signs-board")), [before] + ims))
    grid(rows, Image, ImageDraw, "LITTLE HOP - interest pieces, each alone on today's course (board signs); "
         "x%d (tufts x2)" % ZOOM, ["today (CGA)", "with it (CGA)", "with it (Hercules)"]
         ).save(os.path.join(out, "extras-sheet.png"))
    for n in res:
        cga, herc = pics[n]
        cga.save(os.path.join(out, "full-%s-cga.png" % n))
        herc.save(os.path.join(out, "full-%s-herc.png" % n))
    with open(os.path.join(out, "costs.txt"), "w") as f:
        f.write("variant            compile  stored    LZB    LZ4  blocks  records   vs no signs\n")
        for n, (c, m) in res.items():
            f.write("%-18s %-7s %7d %6d %6d %7d %8d   %s\n" % (n, "ok" if m["ok"] else "FAILED", m["stored"], m["lzb"],
                                                             m["lz4"], m["blocks"], m["records"], cost(n)))
    print("sheet: %s" % out)


def main():
    if len(sys.argv) > 1 and sys.argv[1] == "sheet":
        return sheet(sys.argv[2] if len(sys.argv) > 2 else "hop-art")
